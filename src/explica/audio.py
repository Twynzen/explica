"""Audio: separate voice / music / effects from the start.

- Voice: optional local TTS (Piper, MIT; voices carry their own dataset
  license) as a *placeholder* narration that a human recording can replace via
  `asset.replace` without touching the timeline. No cloud TTS, no voice cloning.
- Music: original synthesized pad generated with FFmpeg's lavfi sources, so no
  third-party audio is ever bundled.
- Mastering: two-pass loudnorm towards the project target (default −16 LUFS,
  −1 dBTP), then measured again with ebur128 (A09).
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from .media import loudness
from .tools import run


def piper_available() -> bool:
    try:
        import piper  # noqa: F401

        return True
    except Exception:
        return False


def synthesize_voice(text: str, out_wav: Path, model_path: Path, length_scale: float = 1.0, sentence_silence: float = 0.25) -> dict:
    """Synthesize `text` to a 48 kHz mono WAV with Piper (local)."""
    from piper import PiperVoice  # type: ignore

    out_wav = Path(out_wav)
    out_wav.parent.mkdir(parents=True, exist_ok=True)
    raw = out_wav.with_suffix(".raw22k.wav")
    import wave

    voice = PiperVoice.load(str(model_path))
    try:
        from piper import SynthesisConfig  # type: ignore

        cfg = SynthesisConfig(length_scale=length_scale)
    except Exception:  # older piper
        cfg = None
    with wave.open(str(raw), "wb") as fh:
        if cfg is not None:
            voice.synthesize_wav(text, fh, syn_config=cfg)
        else:
            voice.synthesize_wav(text, fh)
    ffmpeg = shutil.which("ffmpeg")
    # resample to 48 kHz, add a short tail of silence so clips never cut a phoneme
    run([ffmpeg, "-v", "error", "-y", "-i", str(raw), "-af", f"apad=pad_dur={sentence_silence}", "-ar", "48000", "-ac", "1", "-c:a", "pcm_s16le", str(out_wav)])
    raw.unlink(missing_ok=True)
    return {"path": str(out_wav), "model": Path(model_path).name, "text": text, "sample_rate": 48000}


def generate_music(out_wav: Path, seconds: float, seed: int = 7, gain_db: float = -22.0) -> dict:
    """Original ambient pad: three detuned sines with slow tremolo, low-passed. Deterministic for a seed."""
    ffmpeg = shutil.which("ffmpeg")
    base = 110.0 + (seed % 5) * 11.0
    f1, f2, f3 = base, base * 1.5, base * 2.0 + 0.7
    graph = (
        f"sine=f={f1}:d={seconds}[a];sine=f={f2}:d={seconds}[b];sine=f={f3}:d={seconds}[c];"
        f"[a][b][c]amix=inputs=3:normalize=0,tremolo=f=0.11:d=0.5,lowpass=f=900,"
        f"afade=t=in:d=2,afade=t=out:st={max(0.0, seconds - 3)}:d=3,volume={gain_db}dB,aformat=sample_rates=48000:channel_layouts=stereo"
    )
    out_wav = Path(out_wav)
    out_wav.parent.mkdir(parents=True, exist_ok=True)
    run([ffmpeg, "-v", "error", "-y", "-filter_complex", graph, "-c:a", "pcm_s16le", str(out_wav)])
    return {"path": str(out_wav), "seconds": seconds, "seed": seed, "license": "generated by explica (original, CC0)"}


def normalize_loudness(src: Path, out: Path, target_lufs: float = -16.0, true_peak: float = -1.0, lra: float = 11.0) -> dict:
    """Two-pass EBU R128 loudnorm; keeps video stream untouched (copy)."""
    ffmpeg = shutil.which("ffmpeg")
    first = run([ffmpeg, "-v", "info", "-nostats", "-i", str(src), "-vn", "-af", f"loudnorm=I={target_lufs}:TP={true_peak}:LRA={lra}:print_format=json", "-f", "null", "-"], check=False)
    text = first.stderr
    start = text.rfind("{")
    measured = json.loads(text[start:text.rfind("}") + 1]) if start >= 0 else {}
    af = (
        f"loudnorm=I={target_lufs}:TP={true_peak}:LRA={lra}:measured_I={measured.get('input_i', -24)}:"
        f"measured_TP={measured.get('input_tp', -2)}:measured_LRA={measured.get('input_lra', 7)}:"
        f"measured_thresh={measured.get('input_thresh', -34)}:offset={measured.get('target_offset', 0)}:linear=true:print_format=summary"
    )
    out = Path(out)
    argv = [ffmpeg, "-v", "error", "-y", "-i", str(src), "-af", af, "-ar", "48000"]
    if out.suffix.lower() in (".mp4", ".mov", ".mkv"):
        argv += ["-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart"]
    else:
        argv += ["-vn", "-c:a", "pcm_s16le"]
    argv.append(str(out))
    run(argv)
    after = loudness(out)
    return {"path": str(out), "measured_before": measured, "after": after, "target": {"I": target_lufs, "TP": true_peak}}


def wav_duration_seconds(path: Path) -> float:
    import wave

    with wave.open(str(path), "rb") as fh:
        return fh.getnframes() / fh.getframerate()
